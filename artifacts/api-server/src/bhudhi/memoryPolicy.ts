import type { BhudhiTriggerType } from "../types/bhudhi.js";

/** DOC_14 memory read policy — which memory types each trigger may read. */
export const MEMORY_READ_POLICY: Record<string, string[]> = {
  GOAL_STRUCTURING: ["GOAL_CONTEXT", "USER_PREFERENCE"],
  TASK_DRAFTING: ["USER_PREFERENCE", "CAPABILITY_NOTE"],
  TASK_CLARIFICATION: [],
  FEEDBACK_CLASSIFICATION: ["FRICTION_PATTERN"],
  RECOVERY_COPY: ["RECOVERY_CONTEXT", "FRICTION_PATTERN"],
  STATE_EXPLANATION: ["EXECUTION_PATTERN", "GOAL_CONTEXT"],
  ACADEMY_SUPPORT: ["CAPABILITY_NOTE"],
  OUTCOME_EVIDENCE_SUMMARY: ["GOAL_CONTEXT"],
  ROOT_CAUSE_ASSIST: ["EXECUTION_PATTERN", "FRICTION_PATTERN"],
  CLARIFICATION_PROMPT: [],
  INACTIVITY_RESTART: ["RECOVERY_CONTEXT", "EXECUTION_PATTERN"],
};

export const MAX_MEMORY_ITEMS_PER_CALL = 5;
export const MIN_RELEVANCE_SCORE = 0.4;
export const MAX_MEMORY_CONTENT_CHARS = 500;

export function allowedMemoryTypesForTrigger(triggerType: BhudhiTriggerType | string): string[] {
  if (triggerType in MEMORY_READ_POLICY) {
    return MEMORY_READ_POLICY[triggerType]!;
  }
  const extended = MEMORY_READ_POLICY_EXTENDED as Record<string, string[] | undefined>;
  return extended[triggerType] ?? [];
}

